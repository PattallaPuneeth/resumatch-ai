"""
Builds the `score_details` eval set from the "Resume and Job Description Matching Dataset"
(resume-score-details: 1,031 JSON files; JDs and scores generated by GPT-4o, resumes real).

Each JSON has the resume, a JD, the JD's minimum requirements, and GPT-4o's output: micro and
macro scores (0-10) and a met / not met flag per minimum requirement. Only files that GPT-4o
marked valid, from the `match`, `mismatch` and `empty_additional_info` groups, are used; the
invalid / gibberish groups are left out.

Labels are GPT-4o's, not a person's. They are mapped to strong / medium / weak with a fixed rule
(see `gpt_label`), and the raw scores are kept in labels.csv so the rule can be changed after the
labels are checked against a human sample.

Selection and hygiene:
  - one row per (resume, JD). GPT-4o scored 166 pairs more than once and often disagreed
    with itself (100 differ by a point or more), so repeats are averaged and the spread is kept
  - split by JD: every JD is either `test` or `tune`. The 26 JDs share most of their resumes,
    so the same person can appear in both splits (with a different JD); keeping people apart
    would leave almost no tune data
  - emails, phone numbers and URLs scrubbed, including spaced-out forms ("name. 42@example. com");
    names stay in the resume text, so the output goes to a gitignored folder like real_fit.
    Only the manifest (ids, labels, scores) is committed
  - the JD's markdown heading becomes a "Job Title:" first line, as a user would type it

Usage:
    python -m ml.eval.build_score_details_dataset [--src resume-score-details] \
        [--out ml/eval/datasets_local/score_details]
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import re
from collections import Counter
from pathlib import Path
from typing import Any

from ml.eval.build_real_fit_dataset import scrub, with_title

USED_GROUPS = ("match", "mismatch", "empty_additional_info")
TEST_PAIR_SHARE = 0.35
_HEADING = re.compile(r"^\s*#+\s*(.+?)\s*#*\s*$")
# Spaced-out or partly scrubbed contact details that the real_fit scrubber does not catch
_LOOSE_EMAIL = re.compile(
    r"[\w.\-]+(?:\s?[\w.\-]+)?\s?@\s?[\w\-\[\]]+(?:\s?\.\s?[a-z]{2,4})*", re.I
)
_LOOSE_PHONE = re.compile(r"\+?\d[\d\s\-()]{8,}\d")


def scrub_strict(text: str) -> str:
    return _LOOSE_PHONE.sub("[phone]", _LOOSE_EMAIL.sub("[email]", scrub(text)))


def short_hash(text: str) -> str:
    return hashlib.sha256(" ".join(text.split()).encode("utf-8")).hexdigest()[:12]


def gpt_label(micro: float, req_met: int, req_n: int) -> str:
    """
    GPT-4o's scores as a band. Strong needs every minimum requirement met and a high skill
    score; any unmet requirement caps the pair at medium; a low skill score is weak.
    """
    all_met = req_n > 0 and req_met == req_n
    if micro >= 7.0 and all_met:
        return "strong"
    if micro < 4.0 or (req_n > 0 and req_met / req_n < 0.5):
        return "weak"
    return "medium"


def clean_title(text: str) -> str:
    """'Join **Acme** as a **Senior PM**' or 'Job Title: Lead Engineer at X' -> the role alone."""
    t = text.replace("*", "").replace("#", "").strip()
    t = re.sub(r"^(?:(?:job\s+title|title|position|role)\s*:\s*)+", "", t, flags=re.I)
    t = re.sub(r"^join\b.*?\bas\s+(?:an?\s+)?", "", t, flags=re.I)
    t = re.split(r"\s+(?:where|who|to)\s+|[!,(]", t)[0]
    t = re.split(r"\s+(?:at|with|-|–|\|)\s+[A-Z\[]", t)[0]
    return " ".join(t.split()[:8]).strip(" .:") or "Job"


def job_title(jd: str) -> str:
    """The role from the JD's first markdown heading, else from its first line."""
    for line in jd.splitlines():
        m = _HEADING.match(line)
        if m:
            return clean_title(m.group(1))
        if line.strip():
            return clean_title(line)
    return "Job"


def read_pairs(src: Path) -> list[dict[str, Any]]:
    pairs: dict[tuple[str, str], dict[str, Any]] = {}
    for f in sorted(src.glob("*.json")):
        group = re.sub(r"_\d+\.json$", "", f.name)
        if group not in USED_GROUPS:
            continue
        d = json.loads(f.read_text(encoding="utf-8"))
        inp, out = d.get("input") or {}, d.get("output") or {}
        resume, jd = (inp.get("resume") or "").strip(), (inp.get("job_description") or "").strip()
        scores = out.get("scores") or {}
        micro = (scores.get("aggregated_scores") or {}).get("micro_scores")
        if not out.get("valid_resume_and_jd") or not resume or not jd or micro is None:
            continue
        reqs = scores.get("requirements") or []
        key = (short_hash(resume), short_hash(jd))
        p = pairs.setdefault(key, {
            "resume_id": key[0], "jd_id": key[1], "resume": resume, "jd": jd, "group": group,
            "micros": [], "macros": [], "req_n": len(reqs), "met_runs": [], "unmet": set(),
        })
        agg = scores.get("aggregated_scores") or {}
        p["micros"].append(float(micro))
        p["macros"].append(float(agg.get("macro_scores") or 0.0))
        p["met_runs"].append(sum(bool(r.get("meets")) for r in reqs))
        p["unmet"].update(str(r.get("criteria", "")) for r in reqs if not r.get("meets"))
    out = []
    for p in pairs.values():
        # Average GPT-4o's repeated runs; requirements count as met only if met in every run
        out.append({**p, "micro": sum(p["micros"]) / len(p["micros"]),
                    "macro": sum(p["macros"]) / len(p["macros"]), "req_met": min(p["met_runs"]),
                    "runs": len(p["micros"]), "spread": max(p["micros"]) - min(p["micros"]),
                    "unmet": sorted(p["unmet"])})
    return out


def split_by_jd(pairs: list[dict[str, Any]]) -> list[dict[str, Any]]:
    per_jd = Counter(p["jd_id"] for p in pairs)
    test_jds: set[str] = set()
    for jd in sorted(per_jd):  # ids are hashes, so this is a fixed pseudo-random order
        if sum(per_jd[j] for j in test_jds) >= TEST_PAIR_SHARE * len(pairs):
            break
        test_jds.add(jd)
    return [{**p, "split": "test" if p["jd_id"] in test_jds else "tune"} for p in pairs]


def build(src: Path, out: Path) -> dict[str, object]:
    pairs = split_by_jd(read_pairs(src))
    (out / "resumes").mkdir(parents=True, exist_ok=True)
    (out / "jobs").mkdir(parents=True, exist_ok=True)
    rows = []
    for p in sorted(pairs, key=lambda p: (p["split"], p["jd_id"], p["resume_id"])):
        job_file, resume_file = f"job_{p['jd_id']}.txt", f"resume_{p['resume_id']}.txt"
        (out / "jobs" / job_file).write_text(
            with_title(scrub_strict(p["jd"]), job_title(p["jd"])), encoding="utf-8")
        (out / "resumes" / resume_file).write_text(scrub_strict(p["resume"]), encoding="utf-8")
        label = gpt_label(p["micro"], p["req_met"], p["req_n"])
        rows.append({
            "resume": resume_file, "job": job_file, "expected": label,
            "reason": f"GPT-4o label: micro {p['micro']:.2f}, {p['req_met']}/{p['req_n']} "
                      "minimum requirements met; not human-verified",
            "split": p["split"], "source": f"resume_score_details:{p['group']}",
            "gpt_micro": f"{p['micro']:.2f}", "gpt_macro": f"{p['macro']:.2f}",
            "req_met": str(p["req_met"]), "req_n": str(p["req_n"]),
            "gpt_runs": str(p["runs"]), "gpt_micro_spread": f"{p['spread']:.2f}",
            "unmet_requirements": " | ".join(p["unmet"]),
        })
    with open(out / "labels.csv", "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
    return {
        "pairs": len(rows),
        "jobs": len({r["job"] for r in rows}),
        "resumes": len({r["resume"] for r in rows}),
        "by_split": dict(Counter(r["split"] for r in rows)),
        "by_label": dict(Counter(r["expected"] for r in rows)),
        "by_split_label": dict(Counter(f"{r['split']}:{r['expected']}" for r in rows)),
        "resumes_in_both_splits": len({r["resume"] for r in rows if r["split"] == "test"}
                                      & {r["resume"] for r in rows if r["split"] == "tune"}),
        "repeated_pairs": sum(r["gpt_runs"] != "1" for r in rows),
        "repeats_differing_by_1_or_more": sum(float(r["gpt_micro_spread"]) >= 1 for r in rows),
    }


def main() -> None:
    p = argparse.ArgumentParser(description="Build the score_details eval set")
    p.add_argument("--src", default="resume-score-details")
    p.add_argument("--out", default="ml/eval/datasets_local/score_details")
    a = p.parse_args()
    print(json.dumps(build(Path(a.src), Path(a.out)), indent=2))


if __name__ == "__main__":
    main()
